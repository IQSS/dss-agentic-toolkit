#!/usr/bin/env python3
"""Slice a single-file document into one Quarto page per chapter.

Used by both agentic-AI sites (dss-agentic-research, dss-agentic-toolkit) from their `just sync`.
See training/dss-training-ops/docs/plans/2026-08-30-agentic-sites-conversion-plan.md, Phase 2.

The chapters are *slices*, not renderings. This script never round-trips the markdown through
pandoc's AST, because a read-and-write pass reflows tables, renumbers lists and normalises
emphasis -- silent corruption in a document whose Appendix A must match section 6 byte for byte.
Every content transformation belongs in the render-time Lua filter instead. What happens here is
line surgery: find the H1s, cut between them, add a YAML title.

What it writes into the site repository:

    source/<name>.md      a copy of the upstream markdown -- the drift boundary
    figures/*.svg         the web-format figures, copied from upstream
    chapters/NN-slug.qmd  one page per H1
    filters/site-filter.lua  the render-time filter, copied so CI needs only this repository
    site.css              its styling counterpart, copied for the same reason
    figures-dark.css      generated: swaps each figure for its dark-mode twin
    scripts/              this script and check-site.py, so CI can run both checks
    SOURCE.lock           upstream repo, commit, path, sha256 of the copy
    _quarto.yml           the sidebar contents and the chapter map, between generated markers

Run it from anywhere:

    split-chapters.py --upstream ../../publishing/agentic-ai-for-researchers --site .

and in CI, where there is no upstream to reach, check that what is committed is what the committed
source produces:

    split-chapters.py --check --site .
"""

from __future__ import annotations

import argparse
import hashlib
import json
import math
import re
import shutil
import subprocess
import sys
from pathlib import Path

BEGIN_SIDEBAR = "# BEGIN chapters -- generated by split-chapters.py, do not edit"
END_SIDEBAR = "# END chapters"
BEGIN_MAP = "# BEGIN chapter-map -- generated by split-chapters.py, do not edit"
END_MAP = "# END chapter-map"
PLACEHOLDER = re.compile(r"^\s*# chapters are added here when the content pipeline runs.*$", re.M)

# A fence opens with three or more backticks or tildes, indented at most three spaces, and closes
# with at least as many of the same character. Tracking this is not optional: both documents carry
# shell and R comments at column 0 inside code blocks ("# Tasks", "# justfile", "# heat-birthweight"),
# and a naive ^# scan would cut the document at every one of them.
FENCE = re.compile(r"^ {0,3}(?P<char>`{3,}|~{3,})(?P<info>.*)$")

# What the sync copies out of this directory into a site, as (source name, destination path). These
# have to live in the site because CI clones it alone. check-upstream.py reads this list, so that a
# file added here is a file the next check knows a site should have.
COPIED_TOOLING = (
    ("site-filter.lua", "filters/site-filter.lua"),
    ("site.css", "site.css"),
    ("prompt-controls.html", "prompt-controls.html"),
    ("split-chapters.py", "scripts/split-chapters.py"),
    ("check-site.py", "scripts/check-site.py"),
    ("render-site.py", "scripts/render-site.py"),
)

H1 = re.compile(r"^# (?P<text>.+?)\s*$")
EXPLICIT_ID = re.compile(r"\s+\{#(?P<id>[a-z][a-z0-9]*(?:-[a-z0-9]+)*)\}\s*$")
NUMBERED = re.compile(r"^(?P<num>\d+)\.\s+(?P<rest>.+)$")
APPENDIX = re.compile(r"^Appendix\s+(?P<letter>[A-Z])\.\s+(?P<rest>.+)$")
PART_MARKER = re.compile(r"^<!--\s*=+\s*(?P<title>.+?)\s*=+\s*-->\s*$")
ROMAN = re.compile(r"^[IVXLC]+$")


def slugify(text: str) -> str:
    """Lowercase, ASCII, hyphen-separated. Punctuation and accents go; word order stays."""
    text = text.replace("’", "").replace("'", "")
    text = re.sub(r"[‐-―]", "-", text)  # every dash Unicode offers
    text = re.sub(r"[^a-zA-Z0-9]+", "-", text)
    return re.sub(r"-+", "-", text).strip("-").lower()


def title_case_part(text: str) -> str:
    """`PART I — ORIENTATION` -> `Part I — Orientation`. Roman numerals keep their case."""
    return " ".join(w if ROMAN.match(w) else w.capitalize() for w in text.split())


def frontmatter_end(lines: list[str]) -> int:
    """Index of the first line after a leading YAML frontmatter block, or 0 when there is none.

    Frontmatter can carry YAML comments, and a comment starts with `# `, which is exactly an H1 to
    this splitter: on 2026-09-11 a comment in the guide's frontmatter became a chapter page. Nothing
    above this index is searched for headings or part markers.
    """
    if not lines or lines[0].rstrip() != "---":
        return 0
    for i in range(1, len(lines)):
        if lines[i].rstrip() in ("---", "..."):
            return i + 1
    sys.exit("error: unterminated YAML frontmatter -- the split would be wrong, refusing")


def find_chapters(lines: list[str]) -> tuple[list[dict], list[dict]]:
    """Return (chapters, parts). Each chapter is {num, key, title, slug, start, end}.

    `start` is the index of the H1 line; `end` is one past the last body line. Parts record the
    index of the marker comment so a chapter can be attributed to the part it falls under.
    """
    chapters: list[dict] = []
    parts: list[dict] = []
    fence: str | None = None
    skip = frontmatter_end(lines)

    for i, line in enumerate(lines):
        if i < skip:
            continue
        m = FENCE.match(line)
        if m:
            char = m.group("char")
            if fence is None:
                fence = char
            elif char[0] == fence[0] and len(char) >= len(fence) and not m.group("info").strip():
                fence = None
            continue
        if fence is not None:
            continue

        part = PART_MARKER.match(line)
        if part:
            parts.append({"index": i, "title": title_case_part(part.group("title"))})
            continue

        head = H1.match(line)
        if not head:
            continue
        text = head.group("text")
        explicit = EXPLICIT_ID.search(text)
        identifier = explicit.group("id") if explicit else None
        if explicit:
            text = text[:explicit.start()].rstrip()
        elif "{#" in text:
            sys.exit(f"error: invalid chapter id on line {i + 1}; use {{#lowercase-kebab-id}}")
        num = NUMBERED.match(text)
        app = APPENDIX.match(text)
        if num:
            key, slug = num.group("num"), f"{int(num.group('num')):02d}-{slugify(num.group('rest'))}"
        elif app:
            key = app.group("letter")
            slug = f"appendix-{key.lower()}-{slugify(app.group('rest'))}"
        else:
            # An unnumbered chapter (the tool-chain's Introduction). Sorts first, cited as nothing.
            key, slug = None, f"00-{slugify(text)}"
        if identifier:
            slug = identifier
        if any(chapter["slug"] == slug for chapter in chapters):
            sys.exit(f"error: duplicate chapter id or filename {slug!r} on line {i + 1}")
        chapters.append({"key": key, "title": text, "slug": slug, "start": i,
                         "identifier": identifier})

    if fence is not None:
        sys.exit(f"error: unterminated code fence ({fence}) -- the split would be wrong, refusing")
    if not chapters:
        sys.exit("error: no H1 found outside code fences")

    for a, b in zip(chapters, chapters[1:] + [{"start": len(lines)}]):
        a["end"] = b["start"]
    for c in chapters:
        c["part"] = next((p["title"] for p in reversed(parts) if p["index"] < c["start"]), None)
    return chapters, parts


def body_of(lines: list[str], chapter: dict) -> str:
    """Everything after the H1 line, trimmed of blank lines at both ends and of part markers.

    The H1 itself goes: Quarto renders the page title as the H1, and a second one would duplicate it.
    """
    body = [ln for ln in lines[chapter["start"] + 1:chapter["end"]] if not PART_MARKER.match(ln)]
    while body and not body[0].strip():
        body.pop(0)
    while body and not body[-1].strip():
        body.pop()
    return "\n".join(body)


# ---- the chapter agent -------------------------------------------------------------------------
# The landing page draws one robot per chapter from a parts kit (the SVG groups in index.qmd) and a
# recipe (console.js `CH`). The same recipe dresses a static copy at the head of the chapter's own
# page, so the figure a reader hovered on the console is the one that greets them inside. Both inputs
# live in the site repository and are hand-maintained, which is what keeps this site-internal: a
# document with no console.js (the tool-chain) gets no agents and none of this runs.

AGENT_VIEWBOX = "451 -16 346 410"  # measured across every pose, widest held objects included,
                                   # and deep enough for the glassbox caption on y=382

# Scene props that wrap around the figure rather than standing beside it, so they belong in the
# chapter's crop. Boundaries' glassbox is the case this exists for: the whole point of the drawing
# is the container, and a robot shipped without it is the figure with its subject removed.
ENCLOSING_SCENES = frozenset({"glassbox"})

CH_ENTRY = re.compile(r'\{\s*n:\s*"(?P<n>[^"]+)".*?slug:\s*"[^"]+".*?r:\s*\{(?P<r>[^}]*)\}', re.S)


def _js_literal(js: str, name: str) -> str:
    """The text of `const NAME = <literal>;`, matched on its own brackets rather than a line."""
    m = re.search(rf"const\s+{name}\s*=\s*", js)
    if not m:
        sys.exit(f"error: console.js has no `const {name}` -- the chapter agents cannot be built")
    i = m.end()
    opener = js[i]
    closer = {"{": "}", "[": "]"}[opener]
    depth, j, quote = 0, i, None
    while j < len(js):
        c = js[j]
        if quote:
            if c == "\\":
                j += 2
                continue
            if c == quote:
                quote = None
        elif c in "\"'":
            quote = c
        elif c == opener:
            depth += 1
        elif c == closer:
            depth -= 1
            if depth == 0:
                return js[i:j + 1]
        j += 1
    sys.exit(f"error: console.js `const {name}` is unterminated")


def _js_obj(text: str):
    """A JS literal of plain scalars -> Python. Quotes bare keys, drops trailing commas, then JSON."""
    t = re.sub(r"([{,\[]\s*)([A-Za-z_][A-Za-z0-9_]*)\s*:", r'\1"\2":', text)
    t = re.sub(r",(\s*[}\]])", r"\1", t)
    return json.loads(t)


def _recipe(text: str) -> dict:
    return {k: (None if v == "null" else v.strip('"'))
            for k, v in re.findall(r'(\w+):\s*(null|"[^"]*")', text)}


def _group(markup: str, opening: re.Match) -> int:
    """Index one past the `</g>` that closes the group `opening` starts."""
    depth, k = 1, opening.end()
    while depth:
        nxt = re.search(r"<g\b|</g>", markup[k:])
        if not nxt:
            sys.exit("error: unbalanced <g> in the parts kit -- refusing to build the agents")
        k += nxt.end()
        depth += 1 if nxt.group() == "<g" else -1
    return k


def _svg_group(qmd: str, gid: str) -> str:
    m = re.search(rf'<g id="{gid}"[^>]*>', qmd)
    if not m:
        sys.exit(f'error: index.qmd has no <g id="{gid}"> -- the chapter agents cannot be built')
    return qmd[m.start():_group(qmd, m)]


def _keep_parts(markup: str, keep: set[str]) -> str:
    """Drop every `.part` the recipe does not name, and unclass the ones it does.

    The console shows a part by adding a class; a static copy has no script, so the parts that are
    not worn are removed outright rather than left hidden in the markup of all 22 pages.
    """
    found = []
    for m in re.finditer(r'<g class="part" data-part="([^"]+)"', markup):
        opening = re.compile(r"<g\b[^>]*>").match(markup, m.start())
        found.append((m.group(1), m.start(), _group(markup, opening)))
    for name, start, end in reversed(found):
        inner = (re.sub(r'^<g class="part" data-part="[^"]+"', "<g", markup[start:end], count=1)
                 if name in keep else "")
        markup = markup[:start] + inner + markup[end:]
    return markup


def _arm(side: str, a1: float, a2: float, shoulder: dict, seg: dict) -> str:
    sx, sy = shoulder[side]
    sleeve, fore, hand = seg["sleeve"], seg["forearm"], seg["hand"]
    fingers = "".join(f'<rect x="{x}" y="{fore + hand - 4}" width="6" height="12" rx="2" '
                      f'fill="var(--gloves-dk)"/>' for x in (-9, -2, 5))
    return (f'<g transform="translate({sx},{sy}) rotate({a1})">'
            f'<rect x="-13" y="-4" width="26" height="{sleeve + 4}" rx="6" class="coat"/>'
            f'<rect x="-13" y="{sleeve - 8}" width="26" height="9" class="coat-dk"/>'
            f'<circle cx="0" cy="0" r="9" class="coat-dk"/>'
            f'<g transform="translate(0,{sleeve}) rotate({a2})">'
            f'<circle cx="0" cy="0" r="8" fill="var(--c-metal-3)"/>'
            f'<rect x="-10" y="0" width="20" height="{fore}" rx="4" fill="var(--c-metal)"/>'
            f'<rect x="-10" y="{fore - 6}" width="20" height="6" fill="var(--c-metal-3)"/>'
            f'<rect x="-12" y="{fore}" width="24" height="{hand}" rx="4" fill="var(--gloves)"/>'
            f'{fingers}'
            f'<rect x="-12" y="{fore}" width="24" height="4" fill="var(--gloves-dk)"/>'
            f"</g></g>")


def _hand(side: str, a1: float, a2: float, shoulder: dict, seg: dict) -> tuple[float, float]:
    sx, sy = shoulder[side]
    d1, d2 = math.radians(a1), math.radians(a1 + a2)
    ex = sx - math.sin(d1) * seg["sleeve"]
    ey = sy + math.cos(d1) * seg["sleeve"]
    reach = seg["forearm"] + seg["hand"] + 10
    return ex - math.sin(d2) * reach, ey + math.cos(d2) * reach


def agent_svg(kit: dict, r: dict) -> str:
    eyes, coat, glove = kit["EYES"][r["eyes"]], kit["COATS"][r["coat"]], kit["GLOVES"][r["gloves"]]
    arms = kit["ARMS"][r["arms"]]
    shoulder, seg = kit["SHOULDER"], kit["SEG"]

    keep = {"antenna" if r["hat"] == "none" else r["hat"]}
    if eyes["brows"]:
        keep.add("brows")
    fig = _keep_parts(kit["figure"], keep)
    fig = re.sub(r'(<circle class="iris"[^>]*?)r="[\d.]+"([^>]*?)fill="[^"]*"',
                 lambda m: f'{m.group(1)}r="{eyes["r"]}"{m.group(2)}fill="{eyes["color"]}"', fig)
    built = _arm("L", *arms["L"], shoulder, seg) + _arm("R", *arms["R"], shoulder, seg)
    fig = fig.replace('<g id="arms"></g>', f'<g id="arms">{built}</g>', 1)
    # The coat and glove colours are set on #figure itself, not a wrapper: console.css declares
    # defaults on #figure, and a variable set on an ancestor would lose to them.
    style = (f'--coat:{coat["c"]};--coat-dk:{coat["dk"]};--coat-lt:{coat["lt"]};'
             f'--gloves:{glove["c"]};--gloves-dk:{glove["dk"]}')
    fig = fig.replace('<g id="figure">', f'<g id="figure" style="{style}">', 1)

    held = ""
    if r["holds"]:
        hx, hy = _hand("R", *arms["R"], shoulder, seg)
        held = _keep_parts(kit["held"], {r["holds"]})
        held = re.sub(r'<g id="held" transform="[^"]*"',
                      f'<g id="held" transform="translate({hx:.1f},{hy:.1f})"', held, count=1)

    # The scene goes first so it sits behind the figure, as it does on the console. Only the props
    # that enclose the robot survive the chapter crop: the tree, database and screens are drawn to
    # the right of the figure to clear the speech bubble and fall outside it entirely, and widening
    # the box to reach them would shrink the robot on all 22 pages to serve three.
    scene = ""
    if r["scene"] in ENCLOSING_SCENES:
        scene = _keep_parts(kit["surround"], {r["scene"]})
    svg = (f'<div class="chapter-agent" aria-hidden="true">'
           f'<svg viewBox="{AGENT_VIEWBOX}" xmlns="http://www.w3.org/2000/svg">'
           f"{scene}{fig}{held}</svg></div>")
    svg = re.sub(r"\s*\n\s*", "", svg)
    if "\n" in svg:
        sys.exit("error: the agent markup contains a newline; a blank line would end the raw HTML "
                 "block and spill markup into the page")
    return svg


def build_agents(site: Path, chapters: list[dict]) -> dict[str, str]:
    """One dressed figure per chapter key, or {} for a site with no console to take them from."""
    js_path, qmd_path = site / "console.js", site / "index.qmd"
    if not (js_path.is_file() and qmd_path.is_file()):
        return {}
    js, qmd = js_path.read_text(), qmd_path.read_text()
    kit = {name: _js_obj(_js_literal(js, name))
           for name in ("COATS", "GLOVES", "EYES", "ARMS", "SHOULDER", "SEG")}
    kit["figure"] = _svg_group(qmd, "figure")
    kit["held"] = _svg_group(qmd, "held")
    kit["surround"] = _svg_group(qmd, "surround")
    agents = {m.group("n"): agent_svg(kit, _recipe(m.group("r")))
              for m in CH_ENTRY.finditer(_js_literal(js, "CH"))}
    absent = [c["key"] for c in chapters if c["key"] and c["key"] not in agents]
    if absent:
        sys.exit("error: console.js has no recipe for chapter(s) " + ", ".join(absent)
                 + " -- add one, or the page would open with no figure")
    return agents


def chapter_text(lines: list[str], chapter: dict, agent: str = "") -> str:
    """The whole .qmd for one chapter: a title, and the body byte for byte.

    With an agent, the figure comes first and the chapter's own H1 is written back in after it. A
    float only wraps the line boxes that follow it, so a title rendered above the body could never
    sit beside the figure; site.css hides Quarto's own title block on the pages that carry one.
    """
    title = chapter["title"].replace('"', '\\"')
    body = body_of(lines, chapter)
    aliases = re.findall(r"^<!-- aliases: ([a-z0-9-]+) -->$", body, re.M)
    extra = "aliases:\n" + "".join(f"  - /chapters/{name}.html\n" for name in aliases) if aliases else ""
    head = f'---\ntitle: "{title}"\n{extra}---\n\n'
    if agent:
        return f'{head}{agent}\n\n# {chapter["title"]}\n\n{body}\n'
    return f"{head}{body}\n"


def content_commit(upstream: Path, rel: Path) -> str:
    """The last commit that touched what a site actually consumes: the source file and the figures.

    Not HEAD. The document's repository also holds a template, a justfile and its own meta-files, and
    a commit to any of those would otherwise mark every site stale -- noise that teaches you to ignore
    the check. This way "stale" means the content changed.
    """
    return git(upstream, "log", "-1", "--format=%H", "--", str(rel), "figures", "resources")


def synced_paths_dirty(upstream: Path, rel: Path) -> str:
    """Uncommitted changes to those same paths, for the same reason."""
    return git(upstream, "status", "--porcelain", "--", str(rel), "figures", "resources")


def git(repo: Path, *args: str) -> str:
    return subprocess.run(["git", "-C", str(repo), *args],
                          capture_output=True, text=True, check=True).stdout.strip()


def replace_block(text: str, begin: str, end: str, block: str, indent: str) -> str | None:
    """Swap the content between two marker lines, keeping the markers. None if they are absent."""
    pattern = re.compile(re.escape(indent + begin) + r".*?" + re.escape(indent + end), re.S)
    if not pattern.search(text):
        return None
    return pattern.sub(lambda _: indent + begin + "\n" + block + "\n" + indent + end, text, count=1)


def sidebar_block(chapters: list[dict], indent: str) -> str:
    """The sidebar `contents:` entries, grouped into `section:` blocks where the document has parts."""
    out: list[str] = []
    current = object()  # a part title no chapter can have, so the first chapter always opens a group
    for c in chapters:
        if c["part"] != current:
            current = c["part"]
            if current is not None:
                out.append(f'{indent}- section: "{current}"')
                out.append(f"{indent}  contents:")
        lead = f"{indent}    - " if current is not None else f"{indent}- "
        out.append(f"{lead}chapters/{c['slug']}.qmd")
    return "\n".join(out)


def map_block(chapters: list[dict]) -> str:
    """Section number -> chapter page, for the render-time filter that turns 'section 12' into a link."""
    out = ["chapter-map:"]
    for c in chapters:
        if c["key"] is None:
            continue
        out.append(f'  "{c["key"]}": /chapters/{c["slug"]}.qmd')
    return "\n".join(out)


def dark_css(figures: list[str]) -> str:
    """Swap each figure for its dark-mode twin, and take the theme's frame off both.

    The theme gives every image in `main` a plate, a border and a slight dimming in dark mode, which
    is right for a screenshot -- a picture of a light thing -- and wrong for a diagram drawn to sit on
    the page. These figures have a dark variant built from the same source, so they need neither.

    `content: url()` rather than two <img> tags: Quarto builds its figure markup from the image before
    any Lua filter sees it, so the swap is easier to make here than there, and only the file actually
    shown is fetched. The paths are relative to this stylesheet, which sits at the site root, so they
    resolve the same whatever depth the page is at and whatever path the site is deployed under.
    """
    lines = [
        "/* Generated by dss-training-ops/scripts/split-chapters.py. Do not edit. */",
        "/* Dark-mode figures: see AGENTS.md § Figures. Rebuild with `just sync`. */",
        "",
        "body.quarto-dark main img[src*=\"figures/\"] {",
        "  background: none;",
        "  border: none;",
        "  padding: 0;",
        "  filter: none;",
        "}",
        "",
    ]
    for name in figures:
        lines.append(f'body.quarto-dark img[src$="{name}.svg"] '
                     f'{{ content: url("figures/{name}-dark.svg"); }}')
    return "\n".join(lines) + "\n"


def heading_id(text: str) -> str:
    """Pandoc's auto-identifier, near enough to match by. Every use of it is validated below."""
    text = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", text)   # link text, not the target
    text = re.sub(r"[`*_]", "", text)
    text = re.sub(r"[^\w\s.-]", "", text, flags=re.UNICODE)
    text = re.sub(r"\s+", "-", text.strip()).lower()
    return re.sub(r"^[^a-z]+", "", text)


def anchor_map(lines: list[str], chapters: list[dict]) -> dict[str, str]:
    """Which chapter owns each in-document anchor target.

    The documents were written as one file, so `[Package manager](#package-manager)` resolved on the
    page. Split into a page per chapter it becomes a dead link unless the target's chapter is named.
    Only the anchors actually linked to are recorded, and every one of them must resolve -- an
    unresolvable anchor is a broken link the split introduced, so it stops the sync.
    """
    owner: dict[str, str] = {}
    fence: str | None = None
    for c in chapters:
        # The chapter's own H1 becomes the page title, which carries no heading anchor of its own,
        # so a link to it is a link to the page with no fragment.
        owner.setdefault(heading_id(c["title"]), f"/chapters/{c['slug']}.qmd")
        if c.get("identifier"):
            owner[c["identifier"]] = f"/chapters/{c['slug']}.qmd"
        for ln in lines[c["start"] + 1:c["end"]]:
            m = FENCE.match(ln)
            if m:
                char = m.group("char")
                if fence is None:
                    fence = char
                elif char[0] == fence[0] and len(char) >= len(fence) and not m.group("info").strip():
                    fence = None
                continue
            if fence is None and re.match(r"^#{2,6} ", ln):
                explicit = EXPLICIT_ID.search(ln)
                ident = explicit["id"] if explicit else heading_id(ln.lstrip("#").strip())
                owner.setdefault(ident, f"/chapters/{c['slug']}.qmd#{ident}")
            if fence is None and re.match(r"^:::+\s+\{", ln):
                match = re.search(r"\{#([a-z][a-z0-9-]*)\b", ln)
                if match:
                    ident = match[1]
                    owner.setdefault(ident, f"/chapters/{c['slug']}.qmd#{ident}")

    wanted = set(re.findall(r"]\(#([^)]+)\)", "\n".join(lines)))
    missing = sorted(a for a in wanted if a not in owner)
    if missing:
        sys.exit("error: these in-document links point at no heading, so the split would break them:\n  "
                 + "\n  ".join("#" + a for a in missing))
    return {a: owner[a] for a in sorted(wanted)}


def anchor_block(anchors: dict[str, str]) -> str:
    if not anchors:
        return ""            # an empty YAML mapping reads back as null, not as {}
    out = ["anchor-map:"]
    for anchor, target in anchors.items():
        out.append(f'  "{anchor}": {target}')
    return "\n".join(out)


def daily_use_block(upstream: Path) -> str:
    """The matrix rows the author marks as everyday tools, read from the upstream print filter.

    That set is the author's, maintained beside the document; copying it here by hand would go stale
    silently. The print filter draws a pill, the site filter adds a class, both from the same list.
    """
    src = upstream / "filters" / "matrix-shade.lua"
    if not src.is_file():
        return ""
    body = src.read_text()
    body = body[body.index("local daily_use"):body.index("}", body.index("local daily_use"))]
    keys = re.findall(r'\["([^"]+)"\]\s*=\s*true', body)
    if not keys:
        sys.exit(f"error: found no daily-use rows in {src}; its table shape changed, so the site "
                 "would silently lose the marks")
    return "daily-use:\n" + "\n".join(f'  - "{k}"' for k in keys)


def check(site: Path) -> int:
    """Regenerate from the site's own copy of the source and report anything that differs.

    This is what makes a hand-edit of a chapter impossible to merge: CI re-runs the generator against
    the copy committed here and fails if the tree it produces is not the tree that is committed. It
    needs no upstream repository and no credential, because the copy is the drift boundary -- whether
    that copy is current is a separate question, answered by SOURCE.lock when a human syncs.

    Read-only. Whatever it finds, it changes nothing.
    """
    sources = sorted((site / "source").glob("*.md"))
    if len(sources) != 1:
        print(f"error: expected exactly one markdown file in {site / 'source'}, found {len(sources)}")
        return 1
    src = sources[0]
    lines = src.read_text().split("\n")
    chapters, _ = find_chapters(lines)
    problems: list[str] = []

    agents = build_agents(site, chapters)
    expected = {f"{c['slug']}.qmd": chapter_text(lines, c, agents.get(c["key"], ""))
                for c in chapters}
    actual = {f.name: f.read_text() for f in sorted((site / "chapters").glob("*.qmd"))}
    for name in sorted(set(expected) | set(actual)):
        if name not in actual:
            problems.append(f"chapters/{name} is missing; re-run `just sync`")
        elif name not in expected:
            problems.append(f"chapters/{name} is not in the source; re-run `just sync`")
        elif actual[name] != expected[name]:
            a, b = actual[name].split("\n"), expected[name].split("\n")
            n = next((i for i, (x, y) in enumerate(zip(a, b)) if x != y), min(len(a), len(b)))
            problems.append(f"chapters/{name} differs from the source at line {n + 1}:\n"
                            f"      committed: {a[n] if n < len(a) else '(end of file)'}\n"
                            f"      source:    {b[n] if n < len(b) else '(end of file)'}")

    light = sorted(f.stem for f in (site / "figures").glob("*.svg") if not f.stem.endswith("-dark"))
    generated = site / "figures-dark.css"
    if not generated.is_file():
        problems.append("figures-dark.css is missing; re-run `just sync`")
    elif generated.read_text() != dark_css(light):
        problems.append("figures-dark.css does not match the figures present; re-run `just sync`")

    conf = (site / "_quarto.yml").read_text()
    blocks = (("sidebar", sidebar_block(chapters, " " * 6)),
              ("chapter-map", map_block(chapters)),
              ("anchor-map", anchor_block(anchor_map(lines, chapters))))
    for label, block in blocks:
        if block and block not in conf:
            problems.append(f"_quarto.yml's generated {label} block is stale; re-run `just sync`")

    lock = dict(line.split(": ", 1) for line in (site / "SOURCE.lock").read_text().splitlines()
                if ": " in line and not line.startswith("#"))
    digest = hashlib.sha256(src.read_bytes()).hexdigest()
    if lock.get("source_sha256") != digest:
        problems.append(f"SOURCE.lock records source_sha256 {lock.get('source_sha256', '(none)')[:12]}… "
                        f"but {src.relative_to(site)} hashes to {digest[:12]}…; re-run `just sync`")
    resource_record = site / "SOURCE.resources.json"
    if not resource_record.exists() or json.loads(resource_record.read_text()) != resource_hashes(site / "resources"):
        problems.append("Downloadable resources differ from SOURCE.resources.json; re-run just sync")

    if problems:
        print(f"{len(problems)} problem(s) -- the committed tree is not what the source produces:")
        for p in problems:
            print(f"  - {p}")
        return 1
    print(f"chapters match the source: {len(chapters)} pages, the sidebar and both maps, "
          f"and SOURCE.lock's hash")
    return 0


def resource_hashes(directory: Path) -> dict[str, str]:
    """Record nested downloadable resources by path and bytes."""
    return {
        str(path.relative_to(directory)): hashlib.sha256(path.read_bytes()).hexdigest()
        for path in sorted(directory.rglob("*")) if path.is_file()
    }


def sync_resources(upstream: Path, site: Path) -> None:
    origin, destination = upstream / "resources", site / "resources"
    expected = resource_hashes(origin)
    for old in destination.rglob("*"):
        if old.is_file() and str(old.relative_to(destination)) not in expected:
            old.unlink()
    for name in expected:
        target = destination / name
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(origin / name, target)
    (site / "SOURCE.resources.json").write_text(json.dumps(expected, indent=2) + "\n")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--upstream", type=Path, help="the document's repository (required unless --check)")
    ap.add_argument("--site", required=True, type=Path, help="the site repository to write into")
    ap.add_argument("--source", type=Path, help="markdown path relative to --upstream (default: source/<name>.md)")
    ap.add_argument("--allow-dirty", action="store_true",
                    help="sync from an upstream working tree with uncommitted changes")
    ap.add_argument("--check", action="store_true",
                    help="regenerate from the site's own source copy and report differences; writes nothing")
    args = ap.parse_args()

    if args.check:
        sys.exit(check(args.site.resolve()))
    if not args.upstream:
        ap.error("--upstream is required unless --check is given")

    upstream, site = args.upstream.resolve(), args.site.resolve()
    rel = args.source or Path("source") / f"{upstream.name}.md"
    src = upstream / rel
    if not src.is_file():
        sys.exit(f"error: no source markdown at {src}")

    # A sync from a dirty tree records a commit that does not contain what was synced. Refuse it,
    # because SOURCE.lock's whole job is to say what the chapters were generated from. Only the paths
    # a site consumes count: an uncommitted edit to the document's own AGENTS.md is not the site's
    # business.
    if synced_paths_dirty(upstream, rel) and not args.allow_dirty:
        sys.exit(f"error: {upstream} has uncommitted changes to {rel} or figures/; "
                 "commit them or pass --allow-dirty")

    text = src.read_text()
    lines = text.split("\n")
    chapters, parts = find_chapters(lines)

    # 1. the copy that is the drift boundary
    (site / rel.parent).mkdir(parents=True, exist_ok=True)
    shutil.copyfile(src, site / rel)
    sync_resources(upstream, site)

    # 2. the web-format figures, light and dark, plus the stylesheet that swaps between them
    svgs = sorted((upstream / "figures").glob("*.svg"))
    (site / "figures").mkdir(exist_ok=True)
    for old in (site / "figures").glob("*.svg"):
        old.unlink()
    for svg in svgs:
        shutil.copyfile(svg, site / "figures" / svg.name)
    light = sorted(f.stem for f in svgs if not f.stem.endswith("-dark"))
    missing = [n for n in light if not (upstream / "figures" / f"{n}-dark.svg").is_file()]
    if missing:
        sys.exit("error: these figures have no dark-mode variant; run `just figures` upstream:\n  "
                 + "\n  ".join(missing))
    (site / "figures-dark.css").write_text(dark_css(light))

    # 3. the render-time filter, its stylesheet, and the two check scripts. All four live in the site
    # repository rather than being reached across to, because CI clones this repository alone and
    # renders it, exactly as a deployment would. They are copies, so an edit made to one of them here
    # is lost at the next sync -- the originals are in dss-training-ops/scripts/.
    here = Path(__file__).parent
    for name, rel_dest in COPIED_TOOLING:
        dest = site / rel_dest
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(here / name, dest)
        if dest.suffix == ".py":
            dest.chmod(0o755)

    # 4. the chapters, replacing whatever was there so a rename cannot leave the old file behind
    out_dir = site / "chapters"
    out_dir.mkdir(exist_ok=True)
    for old in out_dir.glob("*.qmd"):
        old.unlink()
    agents = build_agents(site, chapters)
    for c in chapters:
        (out_dir / f"{c['slug']}.qmd").write_text(chapter_text(lines, c, agents.get(c["key"], "")))

    # 5. provenance
    (site / "SOURCE.lock").write_text(
        "# Generated by dss-training-ops/scripts/split-chapters.py. Do not edit.\n"
        "# What chapters/ was generated from. CI re-runs the generator and compares.\n"
        "# upstream_commit is the last commit that touched the source file or figures/, not HEAD:\n"
        "# a commit to the document's template or meta-files does not make this site stale.\n"
        f"upstream_repo: {git(upstream, 'remote', 'get-url', 'origin')}\n"
        f"upstream_commit: {content_commit(upstream, rel)}\n"
        f"upstream_dirty: {'true' if synced_paths_dirty(upstream, rel) else 'false'}\n"
        f"source_path: {rel}\n"
        f"source_sha256: {hashlib.sha256(src.read_bytes()).hexdigest()}\n"
        f"chapters: {len(chapters)}\n"
        f"figures: {len(svgs)}\n")

    # 6. the sidebar and the chapter map, in _quarto.yml
    qy = site / "_quarto.yml"
    conf = qy.read_text()
    indent = " " * 6  # sidebar contents sit six spaces in
    updated = replace_block(conf, BEGIN_SIDEBAR, END_SIDEBAR, sidebar_block(chapters, indent), indent)
    if updated is None:
        if not PLACEHOLDER.search(conf):
            sys.exit(f"error: {qy} has neither the generated markers nor the scaffold's placeholder "
                     "comment; add the markers under sidebar.contents and re-run")
        updated = PLACEHOLDER.sub(
            indent + BEGIN_SIDEBAR + "\n" + sidebar_block(chapters, indent) + "\n" + indent + END_SIDEBAR,
            conf, count=1)
    anchors = anchor_map(lines, chapters)
    maps = "\n\n".join(b for b in (map_block(chapters), anchor_block(anchors), daily_use_block(upstream)) if b)
    mapped = replace_block(updated, BEGIN_MAP, END_MAP, maps, "")
    if mapped is None:
        mapped = updated.rstrip("\n") + "\n\n" + BEGIN_MAP + "\n" + maps + "\n" + END_MAP + "\n"
    qy.write_text(mapped)

    named = ", ".join(p["title"] for p in parts) or "no parts"
    print(f"{len(chapters)} chapters, {len(light)} figures (light and dark), "
          f"{len(anchors)} cross-page anchors ({named})")
    for c in chapters:
        print(f"  {c['slug']}.qmd")


if __name__ == "__main__":
    main()
